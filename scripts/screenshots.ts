/**
 * Regenerates docs/screenshots/*.png and docs/screenshots/INDEX.md: every page in a meaningful
 * state against throwaway fake machines (browser mode, real server), 380x640 light by default,
 * a few in dark, one at 320 px and some at 1280x800.
 *
 *   pnpm build && cargo build -p sweep-cli --features testutil && pnpm screenshots
 */
