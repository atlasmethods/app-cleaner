test.afterAll(async () => {
  await main?.stop();
  await startup?.stop();
  await fake?.stop();
  const rows = shots.map((s) => `| \`${s.file}\` | ${s.size} | ${s.theme} | ${s.caption} |`).join('\n');
  writeFileSync(
    path.join(OUT, 'INDEX.md'),
    `# ClearSweep screenshots

Generated by \`pnpm screenshots\` (\`scripts/screenshots.ts\`) in browser mode against throwaway fake machines.
Default: 380x640, light theme.

| File | Size | Theme | What it shows |
| --- | --- | --- | --- |
${rows}
`,
  );
});

async function scene(browser: Browser, server: ServerInfo, hash: string, view: View, fn: (page: Page) => Promise<void>): Promise<void> {
  const ctx = await browser.newContext({ viewport: { width: view.w ?? 380, height: view.h ?? 640 }, colorScheme: view.scheme ?? 'light' });
  const page = await ctx.newPage();
  try {
    await page.goto(`${server.url}#${hash}`);
    await expect(page.getByTestId('appbar-title')).toBeVisible();
    await fn(page);
  } finally {
    await ctx.close();
  }
}

async function shoot(page: Page, name: string, caption: string, view: View = {}): Promise<void> {
  const theme = view.scheme ?? 'light';
  const prefix = view.w && view.w >= 900 ? 'wide-' : view.scheme === 'dark' ? 'dark-' : view.w === 320 ? 'w320-' : '';
  const file = `${prefix}${name}.png`;
  await page.waitForTimeout(250); // let transitions settle
  await page.screenshot({ path: path.join(OUT, file) });
  shots.push({ file, caption, size: `${view.w ?? 380}x${view.h ?? 640}`, theme });
}

